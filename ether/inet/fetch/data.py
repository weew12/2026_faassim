"""互联网延迟测量数据结构文件，定义区域到区域延迟样本的统一表示。

================================================================================
架构定位 (Architecture)
================================================================================
本文件定义 3 个公网数据源共用的统一数据结构 Measurement(NamedTuple):
    source       源区域
    destination  目标区域
    avg          平均延迟 (ms)
    max / min    区间,部分数据源提供 (默认 -1 表示未知)

设计: NamedTuple 不可变 + 字段对齐,保证 3 个数据源的 fetch() 返回类型一致。
================================================================================
"""
from typing import NamedTuple


class Measurement(NamedTuple):
    """互联网延迟测量记录，保存源区域、目标区域和测得的延迟值。"""
    # 连接、路由或流的源节点。
    source: str
    # 路由或流量传输的目标节点。
    destination: str

    avg: float
    max: float = -1
    min: float = -1
